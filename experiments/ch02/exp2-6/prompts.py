# -*- coding: utf-8 -*-
"""
实验 2-6 的提示词模板（两阶段流水线）
=====================================
第 1 阶段 抽取（extract）：把一篇论文/论文片段变成结构化 JSON。
第 2 阶段 大纲（outline）：把结构化摘要变成幻灯片大纲 JSON。

设计要点：
- 全程要求模型"只输出 JSON"，但 0.6B 小模型对 JSON 格式并不稳，
  所以 main.py 里对输出做了"截取首个 {...} 块"的兜底解析（见 extract_first_json）。
- 中文提示 + 明确字段，降低小模型跑偏概率。
- 占位符用 <<PAPER>> / <<SUMMARY>> / <<MAX>>，避免与 JSON 示例里的花括号冲突
  （这些字符串不走 str.format，而在 main.py 里用 .replace() 替换）。
"""

# ---------------------------------------------------------------------------
# 第 1 阶段：从论文文本抽取结构化要素
# ---------------------------------------------------------------------------
EXTRACT_SYSTEM = (
    "你是一位严谨的论文阅读助手。你的任务是阅读用户给出的一篇论文（或论文片段），"
    "抽取其关键信息，并以严格的 JSON 返回。不要输出任何解释性文字，只输出 JSON。"
)

EXTRACT_USER = (
    "请阅读下面这篇论文，抽取关键信息，并以严格 JSON 返回，字段如下：\n"
    "{\n"
    '  "title": "论文标题",\n'
    '  "authors": "作者（字符串，多人用、分隔）",\n'
    '  "venue": "发表会议/期刊/年份（字符串，未知写空串）",\n'
    '  "problem": "这篇论文要解决的核心问题（1~2 句）",\n'
    '  "method": "提出的方法/核心思路（2~3 句）",\n'
    '  "contributions": ["贡献点1", "贡献点2", "贡献点3"],\n'
    '  "key_results": ["关键结果/发现1", "关键结果2"],\n'
    '  "conclusions": ["结论1", "结论2"]\n'
    "}\n"
    "只输出上面的 JSON，不要任何额外文字、不要 markdown 代码围栏。\n\n"
    "===== 论文内容开始 =====\n"
    "<<PAPER>>\n"
    "===== 论文内容结束 ====="
)

# ---------------------------------------------------------------------------
# 第 2 阶段：根据结构化摘要生成幻灯片大纲
# ---------------------------------------------------------------------------
OUTLINE_SYSTEM = (
    "你是一位学术汇报幻灯片设计师。你的任务是根据一篇论文的结构化摘要，"
    "设计出一套适合 10~15 分钟口头汇报的幻灯片大纲。请严格以 JSON 返回，不要输出任何解释性文字。"
)

OUTLINE_USER = (
    "下面是一篇论文的结构化摘要（JSON）。请据此设计一套汇报幻灯片大纲，并以严格 JSON 返回：\n"
    "{\n"
    '  "slides": [\n'
    '    {"title": "幻灯片标题", "bullets": ["要点1", "要点2", "要点3"]},\n'
    "    ...\n"
    '    {"title": "总结与启示", "bullets": ["..."]}\n'
    "  ]\n"
    "}\n"
    "要求：\n"
    "1. 第一张建议是『研究背景/问题』，最后一张必须是『总结与启示』。\n"
    "2. 幻灯片总数控制在 <<MAX>> 张以内，每张要点 3~5 条、简洁。\n"
    "3. 只输出上面的 JSON，不要任何额外文字、不要 markdown 代码围栏。\n\n"
    "===== 结构化摘要开始 =====\n"
    "<<SUMMARY>>\n"
    "===== 结构化摘要结束 ====="
)
